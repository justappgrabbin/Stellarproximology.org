export type AppId = 'chat' | 'ingest' | 'builder' | 'browser' | 'terminal' | 'chart' | 'mesh' | 'settings' | 'mir' | 'library' | 'game' | 'fairy';

export type HDType = 'Projector' | 'Generator' | 'Manifestor' | 'Manifesting Generator' | 'Reflector';

